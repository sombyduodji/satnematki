#!/usr/bin/env python3
"""Write the numbers 0 to 100 in Northern Sámi (data/numbers.js), for the classroom.

Every word is built by rule, the tens and then the unit, and checked against Sátni FST's satni.db, opened read-only.

Usage: python3 tools/make_numbers.py [--db PATH]
"""
import argparse
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = Path.home() / "Git/satni-fst/satni.db"
UNITS = ["", "okta", "guokte", "golbma", "njeallje", "vihtta", "guhtta", "čieža", "gávcci", "ovcci"]
TEENS = [f"{unit}nuppelohkái" for unit in UNITS[1:]]
TENS = ["", "logi", "guoktelogi", "golbmalogi", "njealljelogi", "vihttalogi", "guhttalogi", "čiežalogi", "gávccilogi", "ovccilogi"]
ZERO, HUNDRED = "nolla", "čuohti"


def number_word(n):
    if n == 0:
        return ZERO
    if n == 100:
        return HUNDRED
    if n < 10:
        return UNITS[n]
    if n == 10:
        return "logi"
    if n < 20:
        return TEENS[n - 11]
    return TENS[n // 10] + UNITS[n % 10]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    args = parser.parse_args()
    db = sqlite3.connect(f"file:{args.db}?mode=ro&immutable=1", uri=True)
    known = {r[0] for r in db.execute("SELECT sme_lemma FROM dictionary WHERE pos = 'Num' OR sme_lemma = 'nolla'")}
    words = [number_word(n) for n in range(101)]
    missing = [w for w in words if w not in known]
    if missing:
        raise SystemExit(f"Numbers not in the dictionary: {missing}")
    out = ROOT / "data/numbers.js"
    out.write_text("// Generated by tools/make_numbers.py. The position in the list is the number.\nwindow.MAHTTE_NUMBERS = "
                   + json.dumps(words, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"{len(words)} numbers, all in the dictionary")


if __name__ == "__main__":
    main()
