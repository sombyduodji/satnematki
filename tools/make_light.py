#!/usr/bin/env python3
"""Bake the light of the places the GPU lights (src/gl/) into small maps: art/<place>/light.png and light.js.

The places' own pictures already have their light painted in, by tools/make_store.py, tools/make_classrooms.py and
tools/make_forest.py. This takes the same geometry and sun from those, and writes them down so that the GPU can light what
moves: people, animals, baskets.

Indoors (the grocery store, the two classrooms and the rooms of tools/rooms3d.py) a pixel is one of the world's units on the floor, seen from above (a tile is 16):
  R  sunlight on the floor through the windows, after whatever stands in its way, softened at the edges
  G  how near the ceiling lamps are
  B  the daylight from the windows that isn't direct sun
  A  how high what stands there is, for the light shafts and for shadows

In the forest a pixel is one of the world's pixels on the screen, as its trees' shadows are drawn there:
  R  sunlight on the ground, out of the trees' shadows
  B  how deep in the trees it is, where light shafts show between them

Usage: python3 tools/make_light.py [place …]   (all of them when none is named)
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parent.parent
HEIGHT_TOP = 64  # A's 255 is this high
TILE = 16


def to8(a, shape):
    return np.clip(a * 255 + 0.5, 0, 255).astype(np.uint8).reshape(shape)


def sun_on_floor(p, through, occluders, sun):
    """Through a pane, and not shaded on the way: as the sunny part of lit() in make_store.py and make_classrooms.py."""
    sunny = np.zeros(len(p))
    idx = np.nonzero(through(p))[0]
    for start in range(0, len(idx), 40000):
        part = idx[start:start + 40000]
        q = p[part] + np.array([0, 0, 0.4])
        travel = np.zeros(len(part))
        blocked = np.zeros(len(part), bool)
        for _ in range(22):
            d = occluders(q + sun * travel[..., None])
            blocked |= d < 0.06
            travel += np.maximum(d, 0.6)
        sunny[part[~blocked]] = 1
    return sunny


def occluder_height(p, boxes):
    """The top of whatever stands at each floor point, or 0."""
    top = np.zeros(len(p))
    for (x0, y0, _), (x1, y1, z1) in boxes:
        inside = (p[:, 0] >= x0) & (p[:, 0] <= x1) & (p[:, 1] >= y0) & (p[:, 1] <= y1)
        top[inside] = np.maximum(top[inside], z1)
    return top


def shadow_step(sun):
    """How far a shadow reaches on the screen for each of the world's units of height, as x and y on the screen."""
    ox, oy = -sun[0] / sun[2], -sun[1] / sun[2]
    return [round(float(ox - oy), 4), round(float((ox + oy) / 2), 4)]


def bake_room(name, width, height, room, sun, through, occluders, boxes, lamps, sky, windows_x, windows_y, mullion, window_z, wall_h, ox):
    w, h = width * TILE, height * TILE
    xs, ys = np.meshgrid(np.arange(w) + 0.5, np.arange(h) + 0.5)
    p = np.stack([xs.ravel(), ys.ravel(), np.zeros(xs.size)], axis=1)
    x0, y0, x1, y1 = room
    inside = (p[:, 0] > x0) & (p[:, 1] > y0) & (p[:, 0] < x1) & (p[:, 1] < y1)
    sunny = np.zeros(len(p))
    sunny[inside] = sun_on_floor(p[inside], through, occluders, sun)
    lamp = np.minimum(sum((np.exp(-(((p[:, 0] - lx) ** 2 + (p[:, 1] - ly) ** 2) / 2400)) for lx, ly in lamps), np.zeros(len(p))), 1)
    rgba = np.stack([np.array(Image.fromarray(to8(sunny, (h, w))).filter(ImageFilter.GaussianBlur(0.8))), to8(lamp * inside, (h, w)),
                     to8(sky(p) * inside, (h, w)), to8(occluder_height(p, boxes) / HEIGHT_TOP, (h, w))], axis=-1)
    pad = lambda pairs: [[a * TILE, b * TILE] for a, b in pairs] + [[0, 0]] * (4 - len(pairs))  # four at most, as in src/gl/gl2d.js
    info = {
        "space": "floor", "size": [w, h], "heightTop": HEIGHT_TOP,
        "sun": [round(float(v), 5) for v in sun], "shadowStep": shadow_step(sun),
        "room": [x0, y0, x1, y1], "windowLow": window_z[0], "windowHigh": window_z[1], "wallHigh": wall_h,
        "windowsX": pad(windows_x), "windowsY": pad(windows_y), "mullion": mullion,
        "lamps": [[float(x), float(y)] for x, y in lamps], "ox": ox,
    }
    write(name, rgba, info, int(sunny.sum()))


def write(name, rgba, info, note):
    out = ROOT / "art" / name
    out.mkdir(parents=True, exist_ok=True)
    Image.fromarray(rgba, "RGBA").save(out / "light.png", optimize=True)  # lossless, as A is a height and not a picture
    (out / "light.js").write_text(f"// Generated by tools/make_light.py: the light of this place for the GPU, in the world's units (a tile is 16).\n"
                                  f"(window.MAHTTE_LIGHTS ??= {{}})[{json.dumps(name)}] = {json.dumps(info, separators=(',', ':'))};\n", encoding="utf-8")
    print(name, "light map", rgba.shape[1], "x", rgba.shape[0], note)


def store():
    import make_store as S
    sky = lambda p: np.maximum(np.exp(-np.maximum(p[:, 0] - S.ROOM_X0, 0) / 70) * (p[:, 1] > 10 * TILE),
                               0.7 * np.exp(-np.maximum(p[:, 1] - S.ROOM_Y0, 0) / 70) * (p[:, 0] > 24 * TILE))
    bake_room("store", S.WIDTH, S.HEIGHT, (S.ROOM_X0, S.ROOM_Y0, S.ROOM_X1, S.ROOM_Y1), S.SUN, S.through_a_window, S.occluders, S.OCCLUDERS,
              S.LAMPS, sky, S.WINDOWS_X, S.WINDOWS_Y, [26.7, 1.0], (S.WIN_LOW, S.WIN_HIGH), S.WALL_H, S.OX)


def classroom(name):
    import make_classrooms as C
    room = C.ROOMS[name]
    sky = lambda p: np.exp(-np.maximum(p[:, 0] - room.x0, 0) / 110)
    bake_room(name, room.width, room.height, (room.x0, room.y0, room.x1, room.y1), C.SUN, lambda p: C.through_a_window(room, p),
              lambda p: C.occluders(room, p), room.occluders, [], sky, room.windows, [], [24.6, 0.8], (C.WIN_LOW, C.WIN_HIGH), room.wall_h, room.ox)


def forest():
    import make_forest as F
    # The trees' shadows as make_forest.py lays them on the ground, at half its detail, and then on the world's own pixels.
    F.DETAIL = 2
    shade = F.shadow_layer(0, 0, F.WORLD_W * 2, F.WORLD_H * 2)
    shade = np.array(Image.fromarray((shade * 255).astype(np.uint8)).resize((F.WORLD_W, F.WORLD_H), Image.BILINEAR)) / 255
    sunny = 1 - shade
    # How deep in the trees: the shade spread out, so that it's high in the woods and nothing on open ground.
    deep = np.array(Image.fromarray((shade * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(14))) / 255
    deep = np.clip((deep - 0.12) * 2.2, 0, 1)
    shape = (F.WORLD_H, F.WORLD_W)
    rgba = np.stack([to8(sunny, shape), np.zeros(shape, np.uint8), to8(deep, shape), np.zeros(shape, np.uint8)], axis=-1)
    # On the screen the trees' shadows run 0.72 across and 0.3 down for each 0.62 of their height: the same for whoever walks there.
    info = {"space": "screen", "size": [F.WORLD_W, F.WORLD_H], "sun": [round(float(v), 5) for v in F.SUN], "shadowStep": [0.62 * 0.72, 0.62 * 0.3],
            "lamps": [], "ox": F.OX, "shaftTop": 70}
    write("forest", rgba, info, f"{int((deep > 0.5).sum())} pixels deep in the trees")


def made_room(name, module):
    """A room made with tools/rooms3d.py, by the script that makes it."""
    __import__(module)
    from rooms3d import ROOMS
    room = ROOMS[name]
    bake_room(name, room.width, room.height, (room.x0, room.y0, room.x1, room.y1), room.sun, room.through_a_window, room.occluder_field,
              room.light_boxes(), room.lamps, room.sky_light, room.windows_x, room.windows_y, [room.transom, 0.8], (room.win_low, room.win_high),
              room.wall_h, room.ox)


def made_outdoors(name, module):
    """An outdoor place made with tools/rooms3d.py, such as the car park: lit, as the forest is, on the screen, by where the sun falls."""
    __import__(module)
    from rooms3d import ROOMS, TOP_PAD
    room = ROOMS[name]
    xs, ys = np.meshgrid(np.arange(room.world_w) + 0.5, np.arange(room.world_h) + 0.5)
    u, v = xs.ravel() - room.ox, ys.ravel() - TOP_PAD
    p = np.stack([v + u / 2, v - u / 2, np.zeros(u.size)], axis=1)
    inside = (p[:, 0] > 0) & (p[:, 1] > 0) & (p[:, 0] < room.width * TILE) & (p[:, 1] < room.height * TILE)
    sunny = np.zeros(len(p))
    sunny[inside] = sun_on_floor(p[inside], lambda q: np.ones(len(q), bool), room.occluder_field, room.sun)
    shape = (room.world_h, room.world_w)
    soft = np.array(Image.fromarray(to8(sunny, shape)).filter(ImageFilter.GaussianBlur(0.8)))
    rgba = np.stack([soft, np.zeros(shape, np.uint8), np.zeros(shape, np.uint8), np.zeros(shape, np.uint8)], axis=-1)
    info = {"space": "screen", "size": [room.world_w, room.world_h], "sun": [round(float(c), 5) for c in room.sun], "shadowStep": shadow_step(room.sun),
            "lamps": [], "ox": room.ox, "shaftTop": 0}
    write(name, rgba, info, f"{int(sunny.sum())} pixels in the sun")


PLACES = {"store": store, "classroom": lambda: classroom("classroom"), "lesson": lambda: classroom("lesson"), "forest": forest,
          "library": lambda: made_room("library", "make_library"), "home": lambda: made_room("home", "make_home"),
          "city": lambda: made_outdoors("city", "make_city"), "gearstore": lambda: made_room("gearstore", "make_gearstore")}

if __name__ == "__main__":
    for place in sys.argv[1:] or PLACES:
        PLACES[place]()
